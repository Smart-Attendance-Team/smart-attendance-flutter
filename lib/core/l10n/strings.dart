/// Simple key-based localization (en/ar). Usage: `tr('sign_in')`.
/// Supports placeholders: `tr('err_min', {'name': 'X', 'n': '3'})`.
String tr(String key, [Map<String, String> params = const {}]) {
  final table = AppLocale.isArabic ? _ar : _en;
  var value = table[key] ?? _en[key] ?? key;
  params.forEach((k, v) => value = value.replaceAll('{$k}', v));
  return value;
}

/// Wraps a Latin/number run so it never scrambles inside Arabic text.
String ltr(Object? value) => '\u2066${value ?? ''}\u2069';

